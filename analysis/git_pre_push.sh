# 인천 push 때도 측심 push 때도 돈다(형제 폴더에서 찾는다). **막지 않는다** — 위 일곱과 같은 이유다.
# **닿지 않는 곳:** 값이 맞는지는 안 본다. 대장과 같은지만 본다.
G=$(find_guard "check_site_facts.py") || G=""
