#!/bin/sh
# 정지선 pre-push — 「push는 운영자만」을 **도구 경로가 아니라 대리 여부**로 집행한다.
#
# 왜 이게 따로 필요한가
# ---------------------
# `analysis/hook_stopline.py`(PreToolUse)는 **명령 문자열**을 본다. 그래서
#   python -c "import subprocess; subprocess.run(['git','push'])"
# 같은 간접 호출을 **못 막는다**(2026-08-27 실측: 판정 pass).
# 즉 그 훅의 기전은 「Claude Code 도구 경로 차단」이지 §4 문면의 「운영자만」이 아니다.
#
# 이 훅은 git 자신이 부르므로 **어떤 경로로 왔든** 걸린다.
# 판정 기준은 `CLAUDECODE` — Claude Code가 자기 셸에 심는 표지다(실측).
#   · 운영자가 자기 터미널에서 치면 이 변수가 없다 → 통과. **문서화된 운영자 절차는 그대로다.**
#   · Claude Code 세션에서 나온 push는 직접이든 간접이든 → 차단.
#
# 무엇을 못 하는가 (적어 두지 않으면 또 기전을 문면으로 착각한다)
# ---------------------------------------------------------------
#   1. `.git/hooks/`는 **커밋되지 않는다.** 이 기계에만 있고, 지우면 사라진다.
#      새 clone에는 없다 — `analysis/install_git_hooks.py`로 다시 깐다.
#   2. `CLAUDECODE`는 **지울 수 있다.** 작정한 에이전트는 넘는다.
#      이것은 **내 실수를 막는 난간이지 보안 경계가 아니다.**
#   3. 세션 안에서 `!` 접두로 운영자가 직접 칠 때도 이 변수가 붙어 **같이 막힌다.**
#      그때는 아래 우회 변수를 쓴다.
#
# 운영자 우회 (의도된 통로)
# -------------------------
#   VIDIMUS_PUSH_OK=1 git push
# 정지선-집행: §4 — push는 운영자만
# 정지선-명제: `CLAUDECODE`가 있고 우회 변수가 없으면 **경로와 무관하게** push를 거부한다
# 정지선-한계: `.git/hooks/`는 **커밋되지 않는다**(새 clone엔 없음) · **`CLAUDECODE`는 지울 수 있다** · 세션 안 `!` 접두도 같이 막혀 `VIDIMUS_PUSH_OK=1`이 필요하다. **내 실수를 막는 난간이지 보안 경계가 아니다**


if [ -n "$CLAUDECODE" ] && [ -z "$VIDIMUS_PUSH_OK" ]; then
	echo "" >&2
	echo "정지선: push는 운영자만 한다 (지침 §4)." >&2
	echo "  이 push는 Claude Code 세션(CLAUDECODE=1)에서 나왔다 — 막았다." >&2
	echo "  공개 발행은 운영자의 서명이다. 커밋은 AI 판단, push는 사람 손이다." >&2
	echo "" >&2
	echo "  운영자가 이 세션 안에서 직접 밀어야 하면:  VIDIMUS_PUSH_OK=1 git push" >&2
	echo "  (평소처럼 자기 터미널에서 치면 이 훅은 아무것도 안 한다.)" >&2
	echo "" >&2
	exit 1
fi

# ── 여기부터는 운영자의 push다. 검수 게이트를 한 번 친다 (경고만) ────────────
#
# 지침 §1.4 1층은 편마다 `docs/검수기록.md` 기록 1행 이상을 요구하고,
# §2.3은 `①통독 → ②수치 대조 → ③push` 순서를 정한다. 기록 없이 나가면
# §2.2 표기 블록이 **일어나지 않은 검수를 증언한다.**
#
# 2026-08-27 실측: STATUS 「다음 할 일」의 순서가 `push`를 `#08 검수` 앞에 두고 있었고,
# `report_08`은 미push 42건 안에 **신규(A)**로 들어 있었다. 문서 순서는 고쳤지만
# **문서는 또 틀린다**(§0-3). 그래서 같은 판정을 push 순간에 한 번 더 친다.
#
# **막지 않는다.** 여기서 막히는 것은 운영자의 손이다 —
# `check_status_fresh.py`가 같은 이유로 경고를 기본으로 뒀고 차단 승격을 운영자 판단으로 남겼다.
# 차단이 필요하면 아래 `--hook` 뒤에 `--strict`를 붙인다.
# 검사기가 죽어도 push는 진행된다(`|| true`). 난간이 push를 인질로 잡지 않는다.
# 검사기가 없는 저장소(허브 등)에서는 조용히 건너뛴다 — 그쪽엔 `reports/`가 없다.
if [ -f "analysis/check_review_log.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_review_log.py" --hook >/dev/null || true
fi

# ── 난간 ② 생성물 신선도 (경고) ────────────────────────────────────────────
# CSV 는 새 것인데 지면이 옛 것인 상태를 말한다.
#
# 이 저장소에는 「손으로 옮겨 적지 않는다」를 걸고 생성되는 산출물이 넷 있다.
# **그런데 생성기를 부르는 일 자체는 여전히 손이다.** 다음 달 수집을 돌려 CSV 가
# 바뀌었는데 생성기를 잊으면 지면은 지난달 숫자를 든 채로 남고,
# **그것은 깨져 보이지 않는다** — 숫자가 있고 표가 그려지고 린터도 통과한다.
# 사고 31·55·56 이 전부 같은 얼굴이었다: 같은 값이 두 자리에 있고 한쪽만 갱신된다.
#
# **막지 않는다.** 위와 같은 이유다 — 여기서 막히는 것은 운영자의 손이다.
# 차단이 필요하면 `--hook` 뒤에 `--strict` 를 붙인다.
# **닿지 않는 곳:** 생성기가 인천 저장소에 있어 **허브만 push 하면 건너뛴다.**
# 다만 갈라짐의 원인인 CSV 는 인천에 있으므로 인천 push 때 걸린다. 완전하지 않다.
if [ -f "analysis/check_generated.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_generated.py" --hook >/dev/null || true
fi

# ── 난간 ③ 정본 대장 자체 (경고) ───────────────────────────────────────────
# 린터는 대장을 **믿고** 본문을 검사한다. 그런데 대장 자체를 보는 것이 없었다.
# 2026-08-29에 대장을 50여 행 늘리자 둘이 드러났다 —
# 같은 (값,단위)를 두 번 등재해 **뒤가 앞을 덮은 것**, 그리고 값 칸에 숫자가 없어
# **린터가 통째로 건너뛰는 행**을 넣은 것. 표 안에 있으면서 아무것도 강제되지 않는다.
# **둘 다 대장을 늘릴 때만 생긴다** — 부채를 안 갚는 동안에는 영원히 안 보인다.
#
# **막지 않는다.** 위 둘과 같은 이유다. 차단은 `--strict`.
if [ -f "analysis/check_facts.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_facts.py" >/dev/null 2>&1 || true
fi

# ── 난간 ④ 접근성 표기 (경고) ──────────────────────────────────────────────
# 2026-08-30에 이 축을 **처음** 봤다. 지면 아홉 개를 만들어 놓고 한 번도 안 봤고,
# 보자마자 셋이 나왔다 — 대비 미달(가장 작은 글자에 가장 낮은 대비) · 건너뛰기 링크 부재 ·
# 표에 이름도 머리 방향도 없음.
#
# **셋 다 화면에서는 안 보인다.** 인쇄 판형이 깨져 있던 것과 같은 종류다(사고 68).
# 그래서 push 순간에 한 번 친다 — 새 지면이나 새 표가 붙을 때 조용히 다시 빠지는 것을 막는다.
#
# **막지 않는다.** 위 셋과 같은 이유다. 차단은 `--strict`.
# **닿지 않는 곳:** 표기의 유무만 본다. **대비는 계산하지 않고**(브라우저가 있어야 안다),
# 마크다운 표는 안 본다. **속성이 붙었다는 것은 낭독기가 읽어 준다는 확인이 아니다.**
if [ -f "analysis/check_a11y.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_a11y.py" --hook >/dev/null 2>&1 || true
fi

exit 0
