# ── 난간 ⑦ 공개 저장소에 나가면 안 되는 것 (**차단**) ─────────────────────
# [2026-09-01 운영자 지시] 사이트 어디에도 운영자 실명이 들어가지 않는다(§2.2-3).
# 그날 공개 대상 11곳에 있었고 전부 지웠다. **지운 것은 그때 상태일 뿐이다** —
# 발행 SKILL 이 「새 편은 기준편을 열어 형식을 베껴 쓴다」고 정하므로 표기 블록은
# **베껴지면서 퍼진다.** 실명·개인 이메일·박힌 인증키·로컬 절대경로를 본다.
#
# **[2026-09-09 · 지침 v7.0] 여기만 차단이다.** 다른 일곱이 경고인 이유는 「걸리는 것이 push
# 뒤에도 고쳐진다」인데, **유출은 이력에 남고 지우려면 이력을 다시 써야 한다** — 그건 §4 (가)라
# 운영자 몫이다. **고칠 수 없는 것을 경고로 두면 경고를 못 읽은 순간 끝난다.**
# 종전에는 이 승격이 「운영자 판단」으로 올라가 있었고(B-8), push 가 세션 몫이 된 뒤에도
# 아무도 그 판단을 내리지 않았다. 위 「무엇을 막는가」의 기준이 그 자리를 대신한다.
# **닿지 않는 곳: 이미지 안의 글자와 git 이력을 못 본다.** 이미 나간 것은 이 난간이 못 되돌린다.
G=$(find_guard "check_private.py") || G=""
if [ -n "$G" ] && command -v python >/dev/null 2>&1; then
	if ! python "$G" --hook --strict; then
		echo "" >&2
		echo "  ** push 를 멈춘다 — 공개 저장소에 나가면 안 되는 것이 있다(난간 ⑦). **" >&2
		echo "  고치고 다시 민다. 이미 커밋된 것이면 그 커밋을 고쳐야 하고," >&2
		echo "  **push 된 뒤에는 이력 재작성이라 운영자 몫이다**(지침 §4 가)." >&2
		exit 1
	fi
fi

# ── 난간 ⑧ 사이트 상수 ↔ 대장 (경고) ──────────────────────────────────────
# [2026-09-03] 측심은 지표·부두·판정·챕터 문안의 수치를 코드에 적어 둔다. 대장이 바뀌면
