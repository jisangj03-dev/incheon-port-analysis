#!/bin/sh
# 검증 pre-push — push 순간에 난간 여덟을 한 번 돌린다.
# **일곱은 말하고, 하나(⑦ 공개 유출)만 막는다.**
#
# 이력 (적어 두지 않으면 또 기전을 문면으로 착각한다)
# --------------------------------------------------
# 2026-08-27~09-09 이 훅의 머리에는 「push 는 운영자만」(구 §4) 차단 분기가 있었다 —
# `CLAUDECODE` 가 있고 `VIDIMUS_PUSH_OK` 가 없으면 경로와 무관하게 push 를 거부했다.
# 09-09 운영자 위임으로 push·배포가 세션 몫이 됐고, 지침 v6.4 가 §4 문면을 그에 맞췄다.
# **금지 분기는 지웠다.** 훅은 금지가 아니라 검증에만 쓴다(운영자 위임문 2026-09-09).
# 되돌릴 수 없는 것(힘 push · 토큰 갱신)은 `.claude/settings.json` 의 `permissions.deny` 와
# 자동 모드 `hard_deny` 가 든다. 이 훅이 아니다.
#
# 무엇을 못 하는가
# ----------------
#   1. `.git/hooks/`는 **커밋되지 않는다.** 이 기계에만 있고, 지우면 사라진다.
#      새 clone에는 없다 — `analysis/install_git_hooks.py`로 다시 깐다.
#   2. **일곱은 경고다.** stderr 로 말하고 종료코드는 0 이다 — 읽지 않으면 지나간다.
#
# 무엇을 막는가 — 기준 하나 [지침 v7.0 · 2026-09-09]
# ----------------------------------------------------
# **push 가 되돌릴 수 없게 만드는 것만 막는다.** 종전 기준은 「차단 승격은 운영자 판단」이었는데
# (B-8) push 가 세션 몫이 된 뒤로 그 문장은 **판단을 아무도 안 하는 자리**로 남았다.
# 난간 여덟을 이 기준에 대 보면 갈리는 것은 하나뿐이다 —
#   · 검수 기록 · 생성물 신선도 · 대장 · 접근성 · 셈 · Jekyll · 사이트 상수
#     → 전부 **push 뒤에 고쳐진다.** 고치고 다시 밀면 된다. **경고.**
#   · **공개 유출(⑦)** → 실명·개인 이메일·인증키는 **이력에 남고, 지우려면 이력을 다시 써야 한다.**
#     이력 재작성은 §4 (가)라 운영자 몫이다. **막는 편이 싸다. 차단(`--strict`).**
# 승격 근거(실측 2026-09-09): `--strict` 는 유출에만 실패하고 경고(로컬 절대경로)에는 안 걸린다 —
# 세 저장소 유출 0건 · 종료코드 0. **지금 아무것도 안 막고, 막을 때는 옳은 것을 막는다.**
#
# 정지선-집행: §4 — push 전 검증 여덟. 일곱은 경고 · ⑦ 공개 유출만 차단
# 정지선-명제: push 순간에 검수 게이트·생성물 신선도·대장·접근성·셈·Jekyll·공개 유출·사이트 상수 검사기를 돌리고 stderr 로 말한다 · **⑦ 이 실명·개인 이메일·인증키를 찾으면 그 push 를 막는다**
# 정지선-한계: `.git/hooks/`는 **커밋되지 않는다**(새 clone엔 없음) · **나머지 일곱은 경고라 읽지 않으면 지나간다** · ⑦ 도 **이미지 안의 글자와 git 이력은 못 본다** · push 자체를 판정하지 않는다(금지 분기 삭제)

# ── 인수시험 표지 ───────────────────────────────────────────────────────────
# `install_git_hooks.py --selftest` 는 「어느 환경에서도 통과한다」와 stderr 통과만 시험한다. 아래 난간들은
# 각자 인수시험을 가지므로 여기서 또 돌릴 이유가 없고, [2026-09-03] 개시 검사의 정지 셋이
# **전부 이 인수시험 도중**에 시작했다 — 훅을 네 번 돌리며 저장소 셋의 파일 수백 개를 읽고
# 생성기가 파일을 쓰는 것이 OneDrive 아래에서 정지를 부르는 것으로 보인다(작업기록).
# 표지가 있으면 여기서 끝낸다. 실제 push 에는 이 변수가 없다.
if [ -n "$VIDIMUS_HOOK_SELFTEST" ]; then
	exit 0
fi

# ── 여기부터는 실제 push다. 검수 게이트를 한 번 친다 (경고만) ────────────
#
# 지침 §1.4 1층은 편마다 **결론 자리 수치 1건 이상 원본 대조**를 요구하고, 그 대조는
# `review_pick.py --log` 로 `docs/검수기록.md` 에 남는다. 기록 없이 나가면
# §2.2 표기 블록이 **일어나지 않은 검수를 증언한다.**
#
# 2026-08-27 실측: STATUS 「다음 할 일」의 순서가 `push`를 `#08 검수` 앞에 두고 있었고,
# `report_08`은 미push 42건 안에 **신규(A)**로 들어 있었다. 문서 순서는 고쳤지만
# **문서는 또 틀린다**(§0-3). 그래서 같은 판정을 push 순간에 한 번 더 친다.
#
# **막지 않는다.** 여기서 막히면 push 가 인질이 된다 —
# `check_status_fresh.py`가 같은 이유로 경고를 기본으로 뒀고 차단 승격을 운영자 판단으로 남겼다.
# 차단이 필요하면 아래 `--hook` 뒤에 `--strict`를 붙인다.
# 검사기가 죽어도 push는 진행된다(`|| true`). 난간이 push를 인질로 잡지 않는다.
# 검사기가 없는 저장소(허브 등)에서는 조용히 건너뛴다 — 그쪽엔 `reports/`가 없다.
if [ -f "analysis/check_review_log.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_review_log.py" --hook >/dev/null || true
fi

# ── 검사기 찾기 ────────────────────────────────────────────────────────────
# 난간 ①·③ 은 `analysis/` 를 **현재 저장소 안에서만** 찾는다. 그래서 허브나 측심을
# push 할 때는 조용히 건너뛴다 — 그쪽엔 `analysis/` 가 없기 때문이다. 둘은 인천에만
# 있는 것(push 범위의 `reports/` · 대장)을 보므로 그것으로 족하다.
#
# **나머지는 그 처분이 안 통한다.** ②는 「허브만 push 하면 건너뛴다」를 자기 한계로
# 들고 있었고, ④는 **허브의 지면**을, ⑤는 **허브의 목록**을, ⑥은 **허브의 빌드**를,
# ⑦은 **공개 저장소에 나가는 글자**를 본다 — 즉 **하필 형제 저장소 push 때 꼭 돌아야
# 하는 것들**이다. 붙이기만 하고 안 도는 것은 「장치가 있다」이지 「검사가 됐다」가
# 아니다(사고 26). ⑥⑦ 에 이 함수를 만들면서 ②④⑤ 에 안 번진 것이 사고 87 의 얼굴이었다.
#
# 그래서 형제 폴더에서 찾는다. 이름을 손에 안 든다 — 들면 폴더를 옮길 때 낡는다.
# 검사기들은 자기 `__file__` 로 인천·허브 경로를 잡으므로 **어디서 불러도 같은 것을 본다.**
find_guard() {
	if [ -f "analysis/$1" ]; then
		echo "analysis/$1"
		return 0
	fi
	for d in ../*/; do
		if [ -f "$d/analysis/$1" ]; then
			echo "$d/analysis/$1"
			return 0
		fi
	done
	return 1
}

# ── 난간 ② — 비어 있다 [2026-09-12] ─────────────────────────
# 종전의 ② 는 「생성물 신선도」(`check_generated.py`)였다. 그 장치가 등록한 생성기
# 다섯이 **전부** 한 번도 push 된 적 없는 저장소로 나가고 있었다(사고 115).
# 장치와 생성기를 같이 지웠고, 그래서 이 난간은 **비어 둔다.**
# **번호를 안 당긴다** — ③~⑧ 은 제 자리에 있고, 문서와 표가 그 번호를 가리킨다.
# **살아 있는 생성물(도판·차트 PNG)에는 신선도 검사가 없다** — 없던 구멍이고 지금도 없다.

# ── 난간 ③ 정본 대장 자체 (경고) ───────────────────────────────────────────
# 린터는 대장을 **믿고** 본문을 검사한다. 그런데 대장 자체를 보는 것이 없었다.
# 2026-08-29에 대장을 50여 행 늘리자 둘이 드러났다 —
# 같은 (값,단위)를 두 번 등재해 **뒤가 앞을 덮은 것**, 그리고 값 칸에 숫자가 없어
# **린터가 통째로 건너뛰는 행**을 넣은 것. 표 안에 있으면서 아무것도 강제되지 않는다.
# **둘 다 대장을 늘릴 때만 생긴다** — 부채를 안 갚는 동안에는 영원히 안 보인다.
#
# **막지 않는다.** 위 둘과 같은 이유다. 차단은 `--strict`.
# [2026-09-03] `2>&1` 을 뗐다 — 이 검사는 문제를 stderr 로 말하는데 두 줄기를 다 버리고
# 있었다. 즉 ③④⑤ 는 설치된 날부터 push 때 **한 번도 말할 수 없는** 난간이었다(사고 92).
if [ -f "analysis/check_facts.py" ] && command -v python >/dev/null 2>&1; then
	python "analysis/check_facts.py" >/dev/null || true
fi

# ── 난간 ④ 접근성 표기 (경고) ──────────────────────────────────────────────
# 2026-08-30에 이 축을 **처음** 봤다. 지면 아홉 개를 만들어 놓고 한 번도 안 봤고,
# 보자마자 셋이 나왔다 — 대비 미달(가장 작은 글자에 가장 낮은 대비) · 건너뛰기 링크 부재 ·
# 표에 이름도 머리 방향도 없음.
#
# **셋 다 화면에서는 안 보인다.** 인쇄 판형이 깨져 있던 것과 같은 종류다(사고 68).
# 그래서 push 순간에 한 번 친다 — 새 지면이나 새 표가 붙을 때 조용히 다시 빠지는 것을 막는다.
#
# **막지 않는다.** 위 셋과 같은 이유다. 차단은 `--strict`.
# **닿지 않는 곳:** 표기의 유무만 본다. **대비는 계산하지 않고**(브라우저가 있어야 안다),
# 마크다운 표는 안 본다. **속성이 붙었다는 것은 낭독기가 읽어 준다는 확인이 아니다.**
# [2026-09-03] 형제 폴더에서 찾고(②와 같은 처분 — 이 검사가 보는 지면은 허브에 있다),
# stderr 를 살렸다(사고 92).
G=$(find_guard "check_a11y.py") || G=""
if [ -n "$G" ] && command -v python >/dev/null 2>&1; then
	python "$G" --hook >/dev/null || true
fi

# ── 난간 ⑤ 문장 속의 셈 (경고) ─────────────────────────────────────────────
# 이 저장소의 검사기는 **값**을 잘 본다. 그런데 산문에 적힌 수는 아무도 안 봤다 —
# 「보고서 8편」·「장치 9종」 같은 것. 그리고 그 수는 **매번 낡는다.**
# 2026-08-29 에 「장치 9종」을 고쳤는데 **다음 라운드에 「26종」이 24개 목록 위에 서 있었다.**
#
# 사고 31의 얼굴이되 값이 아니라 **문장**이라 다른 검사기가 안 본다(사고 80).
# **조심으로 안 되는 것은 장치로 막는다**(사고 75와 같은 처분).
#
# **막지 않는다.** 위 넷과 같은 이유다. 차단은 `--strict`.
# **닿지 않는 곳:** 등록한 짝 다섯만 본다. 산문의 모든 수를 세는 것은 불가능하고,
# 시도하면 오탐만 는다. **새로 「N개」를 적을 때 짝을 같이 넣는 것이 규율이다.**
# [2026-09-03] ④와 같다 — 형제 폴더에서 찾고 stderr 를 살렸다(사고 92).
G=$(find_guard "check_counts.py") || G=""
if [ -n "$G" ] && command -v python >/dev/null 2>&1; then
	python "$G" --hook >/dev/null || true
fi

# ── 난간 ⑥ Jekyll 빌드가 깨질 자리 (경고) ─────────────────────────────────
# **허브는 한 번도 빌드된 적이 없다.** 로컬 빌드 수단도 없다. 즉 **첫 push 가
# 곧 첫 빌드**인데 Pages 빌드는 **조용히 죽고**, 허브에는 되돌아갈 옛 판이 없어
# 실패하면 사이트 전체가 404 로 남는다. 다른 난간이 지키는 것들과 성질이 다르다 —
# 저것들은 나간 뒤에도 고쳐지고, 이것은 나간 순간 아무것도 안 보인다.
#
# **막지 않는다.** 위 다섯과 같은 이유다. 차단은 `--strict`.
# **닿지 않는 곳: 이것은 빌드가 아니다** — kramdown 출력·플러그인 버전·Pages
# 고유 제약은 안 본다. PyYAML 이 없으면 「모름」이고 **모름은 통과가 아니다**.
G=$(find_guard "check_jekyll.py") || G=""
